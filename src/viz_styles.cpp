VizPrefs vizStyle(const std::string& name) {
    VizPrefs p = build(T_standard, sizeof(T_standard) / sizeof(T_standard[0]));   // standard first: missing keys keep standard
    if (name == "inverted") { VizPrefs q = build(T_inverted, sizeof(T_inverted) / sizeof(T_inverted[0])); for (auto it = q.begin(); it != q.end(); ++it) p[it.key()] = it.value(); }
    else if (name == "protanopia") { VizPrefs q = build(T_protanopia, sizeof(T_protanopia) / sizeof(T_protanopia[0])); for (auto it = q.begin(); it != q.end(); ++it) p[it.key()] = it.value(); }
    return p;
}
